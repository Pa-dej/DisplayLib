// Ресурспак DisplayLib-icons.zip, собираемый в браузере:
//  - assets/minecraft/textures/item/<name>.png - иконки-предметы блоков без плоской текстуры (лист предметов),
//    чтобы {sprite: "item/barrel"} работал;
//  - assets/displaylib/font/icons.json + textures/font/*.png - шрифт глифов (прямоугольные картинки
//    произвольного размера: {glyph: "gui/sprites/widget/button"}), порядок символов = glyphs.jmc.
import { zipSync, strToU8, type Zippable } from 'fflate';
import itemsJson from './items.json';
import { loadSheet } from './render/items';
import { iconPack } from './render/sprites';
import { glyphRegistry, GLYPH_FIRST_CHAR } from './render/glyphs';

interface ItemsFile { cell: number; items: Record<string, { x: number; y: number }> }
const DATA = itemsJson as ItemsFile;

/** PNG из canvas синхронно (toDataURL): на ~1300 иконок заметно быстрее, чем toBlob через цикл событий. */
function canvasPng(c: HTMLCanvasElement): Uint8Array {
  const b64 = c.toDataURL('image/png').split(',')[1];
  const bin = atob(b64); const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

async function fetchPng(path: string): Promise<Uint8Array | null> {
  try { const r = await fetch(path); if (!r.ok) return null; return new Uint8Array(await r.arrayBuffer()); } catch { return null; }
}

export interface PackResult { blob: Blob; icons: number; glyphs: number; missing: string[] }

export async function buildIconPack(progress?: (msg: string) => void): Promise<PackResult> {
  const files: Zippable = {};
  const meta = { pack: { pack_format: 69, supported_formats: { min_inclusive: 46, max_inclusive: 999 }, min_format: [46, 0], max_format: [999, 0], description: 'DisplayLib: item icons for 3D blocks + glyph font displaylib:icons' } };
  files['pack.mcmeta'] = strToU8(JSON.stringify(meta, null, 2));
  files['README.txt'] = strToU8('DisplayLib icon pack (generated by the screen editor).\n- textures/item/<name>.png: inventory-style icons for blocks without a flat item texture, for {atlas, sprite} text objects.\n- displaylib:icons font: glyphs of any size for {glyph: "..."} segments; order matches plugins/DisplayLib/glyphs.jmc.\n');

  // иконки предметов-блоков из листа
  let icons = 0;
  progress?.('Иконки предметов…');
  const sheet = await loadSheet();
  if (sheet && iconPack.names.length) {
    const c = document.createElement('canvas'); c.width = DATA.cell; c.height = DATA.cell;
    const ctx = c.getContext('2d')!; ctx.imageSmoothingEnabled = false;
    for (const name of iconPack.names) {
      const e = DATA.items[name]; if (!e) continue;
      ctx.clearRect(0, 0, c.width, c.height);
      ctx.drawImage(sheet, e.x, e.y, DATA.cell, DATA.cell, 0, 0, DATA.cell, DATA.cell);
      files['assets/minecraft/textures/item/' + name + '.png'] = [canvasPng(c), { level: 0 }];
      if (++icons % 200 === 0) { progress?.('Иконки: ' + icons + '/' + iconPack.names.length); await new Promise((r) => setTimeout(r, 0)); }
    }
  }

  // шрифт глифов
  const providers: unknown[] = [];
  const missing: string[] = [];
  let cp = GLYPH_FIRST_CHAR, glyphs = 0;
  for (const [name, spec] of Object.entries(glyphRegistry.map)) {
    const ch = String.fromCodePoint(cp++);
    const png = await fetchPng('assets/minecraft/textures/' + name + '.png');
    if (!png) { missing.push(name); continue; }
    const safe = name.replace(/[^a-z0-9_./-]/gi, '_');
    files['assets/displaylib/textures/font/' + safe + '.png'] = [png, { level: 0 }];
    providers.push({ type: 'bitmap', file: 'displaylib:font/' + safe + '.png', height: spec.height, ascent: spec.ascent, chars: [ch] });
    glyphs++;
  }
  if (providers.length) files['assets/displaylib/font/icons.json'] = strToU8(JSON.stringify({ providers }, null, 2));

  progress?.('Сжатие…');
  const zipped = zipSync(files, { level: 6 });
  return { blob: new Blob([zipped as BlobPart], { type: 'application/zip' }), icons, glyphs, missing };
}

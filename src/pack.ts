// Ресурспак DisplayLib-icons.zip, собираемый в браузере:
//  - assets/minecraft/textures/item/<name>.png - иконки-предметы блоков без плоской текстуры (лист предметов),
//    чтобы {sprite: "item/barrel"} работал.
import { zipSync, strToU8, type Zippable } from 'fflate';
import itemsJson from './items.json';
import { loadSheet } from './render/items';
import { iconPack } from './render/sprites';

interface ItemsFile { cell: number; items: Record<string, { x: number; y: number }> }
const DATA = itemsJson as ItemsFile;

/** PNG из canvas синхронно (toDataURL): на ~1300 иконок заметно быстрее, чем toBlob через цикл событий. */
function canvasPng(c: HTMLCanvasElement): Uint8Array {
  const b64 = c.toDataURL('image/png').split(',')[1];
  const bin = atob(b64); const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

export interface PackResult { blob: Blob; icons: number }

export async function buildIconPack(progress?: (msg: string) => void): Promise<PackResult> {
  const files: Zippable = {};
  const meta = { pack: { pack_format: 69, supported_formats: { min_inclusive: 46, max_inclusive: 999 }, min_format: [46, 0], max_format: [999, 0], description: 'DisplayLib: item icons for 3D blocks' } };
  files['pack.mcmeta'] = strToU8(JSON.stringify(meta, null, 2));
  files['README.txt'] = strToU8('DisplayLib icon pack (generated by the screen editor).\n- textures/item/<name>.png: inventory-style icons for blocks without a flat item texture, for {atlas, sprite} text objects.\n');

  // иконки предметов-блоков из листа
  let icons = 0;
  progress?.('Иконки предметов…');
  const sheet = await loadSheet();
  if (sheet && iconPack.names.length) {
    const c = document.createElement('canvas'); c.width = DATA.cell; c.height = DATA.cell;
    const ctx = c.getContext('2d')!; ctx.imageSmoothingEnabled = false;
    for (const name of iconPack.names) {
      const e = DATA.items[name]; if (!e) continue;
      ctx.clearRect(0, 0, c.width, c.height);
      ctx.drawImage(sheet, e.x, e.y, DATA.cell, DATA.cell, 0, 0, DATA.cell, DATA.cell);
      files['assets/minecraft/textures/item/' + name + '.png'] = [canvasPng(c), { level: 0 }];
      if (++icons % 200 === 0) { progress?.('Иконки: ' + icons + '/' + iconPack.names.length); await new Promise((r) => setTimeout(r, 0)); }
    }
  }

  progress?.('Сжатие…');
  const zipped = zipSync(files, { level: 6 });
  return { blob: new Blob([zipped as BlobPart], { type: 'application/zip' }), icons };
}
